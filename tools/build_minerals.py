"""
Bakes the CRISM browse products in data/crism/ into one small mineral grid (data/minerals.js),
so the app can say which minerals are at any point instantly, also offline.

Each browse image stores three spectral band indices as its R, G, B channels
(Viviano-Beck et al. 2014). Per 100 m grid cell we take the mean of the image pixels
inside the cell (pixels with data only) and keep, per mineral, the strongest value over
all scenes and products that measure it. Values are stored as 4-bit codes:
0 = no CRISM coverage, 1..15 = band strength 0..255.

Run: python3 tools/build_minerals.py
"""
import base64, gzip, json, os, re
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
ORDER = ['carbonate', 'clay', 'hydrated', 'olivine', 'pyroxene', 'chlorite']
CHANNELS = {'maf': ['olivine', 'pyroxene', 'pyroxene'], 'car': ['clay', 'carbonate', 'hydrated'], 'pfm': ['chlorite', 'clay', 'clay']}
CELL = 100.0

def load_js(name):
    s = open(os.path.join(ROOT, 'data', name)).read()
    return json.loads(s[s.index('{'):s.rstrip().rstrip(';').rindex('}') + 1])

crism = load_js('crism.js')
dem_txt = open(os.path.join(ROOT, 'data', 'dem.js')).read()
meta = {k: float(re.search(r'"%s":\s*([-0-9.e]+)' % k, dem_txt).group(1)) for k in ['west', 'east', 'south', 'north', 'radius_m']}
lat0 = (meta['south'] + meta['north']) / 2
m_lat = meta['radius_m'] * np.pi / 180
m_lon = m_lat * np.cos(np.radians(lat0))
W = int(round((meta['east'] - meta['west']) * m_lon / CELL))
H = int(round((meta['north'] - meta['south']) * m_lat / CELL))
lons = meta['west'] + (np.arange(W) + 0.5) / W * (meta['east'] - meta['west'])
lats = meta['north'] - (np.arange(H) + 0.5) / H * (meta['north'] - meta['south'])
LON, LAT = np.meshgrid(lons, lats)

best = {k: np.full((H, W), -1.0) for k in ORDER}      # -1 = not covered
for sc in crism['scenes']:
    (s, w), (n, e) = sc['bounds']
    for prod, keys in CHANNELS.items():
        if prod not in sc['files']: continue
        im = np.asarray(Image.open(os.path.join(ROOT, sc['files'][prod])).convert('RGBA')).astype(np.float64)
        ih, iw = im.shape[:2]
        valid = im[:, :, 3] >= 128
        # pixel coordinates of every grid cell centre, and the half-size of a cell in pixels
        px = (LON - w) / (e - w) * iw - 0.5
        py = (n - LAT) / (n - s) * ih - 0.5
        hx = max(1, int(round(CELL / ((e - w) * m_lon / iw) / 2)))
        hy = max(1, int(round(CELL / ((n - s) * m_lat / ih) / 2)))
        inside = (px >= 0) & (py >= 0) & (px < iw) & (py < ih)
        # summed-area tables give the mean over each cell's pixel window
        def sat(a):
            t = np.zeros((ih + 1, iw + 1)); t[1:, 1:] = a.cumsum(0).cumsum(1); return t
        cnt = sat(valid.astype(np.float64))
        sums = [sat(im[:, :, c] * valid) for c in range(3)]
        cx = np.clip(np.round(px).astype(int), 0, iw - 1); cy = np.clip(np.round(py).astype(int), 0, ih - 1)
        x0 = np.clip(cx - hx, 0, iw); x1 = np.clip(cx + hx + 1, 0, iw); y0 = np.clip(cy - hy, 0, ih); y1 = np.clip(cy + hy + 1, 0, ih)
        box = lambda t: t[y1, x1] - t[y0, x1] - t[y1, x0] + t[y0, x0]
        nval = box(cnt)
        ok = inside & (nval >= 6)
        for c, key in enumerate(keys):
            mean = np.where(ok, box(sums[c]) / np.maximum(nval, 1), -1)
            best[key] = np.maximum(best[key], mean)

codes = {k: np.where(best[k] < 0, 0, 1 + np.round(np.clip(best[k], 0, 255) / 255 * 14)).astype(np.uint8) for k in ORDER}
packed = np.zeros((H, W, 3), np.uint8)
for i in range(3):
    packed[:, :, i] = (codes[ORDER[2 * i]] << 4) | codes[ORDER[2 * i + 1]]
raw = packed.tobytes()
obj = {
    'source': 'MRO CRISM MTRDR browse products MAF, CAR, PFM (Viviano-Beck et al. 2014), NASA PDS Geosciences Node; 4 scenes, 2007',
    'method': 'Mean band-index value per 100 m cell, strongest over all scenes; 4-bit code per mineral, 0 = no coverage',
    'width': W, 'height': H, 'cell_m': CELL, 'west': meta['west'], 'east': meta['east'], 'south': meta['south'], 'north': meta['north'],
    'order': ORDER, 'b64': base64.b64encode(gzip.compress(raw, 9)).decode(),
}
with open(os.path.join(ROOT, 'data', 'minerals.js'), 'w') as f:
    f.write('/* Generated by tools/build_minerals.py - do not edit by hand. */\nwindow.MM_MINERALS = ' + json.dumps(obj, separators=(',', ':')) + ';\n')
cov = (codes['olivine'] > 0).mean()
print('grid', W, 'x', H, 'covered %.0f%%' % (cov * 100), 'file', os.path.getsize(os.path.join(ROOT, 'data', 'minerals.js')), 'bytes')
