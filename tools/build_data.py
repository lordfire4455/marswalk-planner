#!/usr/bin/env python3
"""
Build the bundled data files for the Marswalk Planner from raw NASA products.

Usage:
    pip install numpy pillow tifffile imagecodecs
    python tools/build_data.py <raw_dir>

<raw_dir> must contain the files listed in docs/DATA_SOURCES.md (the script
prints which ones are missing). Everything is written to ./data/ as plain
.js / .png files so the app also runs when index.html is opened from disk.
"""
import base64, gzip, json, math, os, sys
import numpy as np
from PIL import Image
import tifffile

RAW = sys.argv[1] if len(sys.argv) > 1 else "raw"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
os.makedirs(os.path.join(OUT, "crism"), exist_ok=True)

MARS_R = 3396190.0  # IAU 2000 sphere used by the DEM projection


def write_js(name, var, obj):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build_data.py - do not edit by hand. */\n")
        f.write("window.%s = %s;\n" % (var, json.dumps(obj, separators=(",", ":"), ensure_ascii=False)))
    print("wrote %-22s %8.1f kB" % (name, os.path.getsize(path) / 1024))


# ----------------------------------------------------------------------------
# 1. Elevation: MRO CTX stereo DTM of Jezero, 20 m/px (USGS, Mars 2020 TRN)
# ----------------------------------------------------------------------------
def build_dem():
    src = os.path.join(RAW, "mmap_jezero_ctx_dem_20m.tif")
    tif = tifffile.TiffFile(src)
    page = tif.pages[0]
    z = page.asarray().astype(np.float64)
    h, w = z.shape
    scale = page.tags["ModelPixelScaleTag"].value if "ModelPixelScaleTag" in page.tags else (20.0, 20.0, 0)
    tie = page.tags["ModelTiepointTag"].value if "ModelTiepointTag" in page.tags else None
    if tie is None:
        x0, y1 = 4573663.250853, 1109693.140188
    else:
        x0, y1 = tie[3], tie[4]
    px = float(scale[0])
    # Equirectangular, lat_ts = 0, lon0 = 0  ->  degrees are linear in x / y.
    west = math.degrees(x0 / MARS_R)
    east = math.degrees((x0 + w * px) / MARS_R)
    north = math.degrees(y1 / MARS_R)
    south = math.degrees((y1 - h * px) / MARS_R)
    assert np.all(z > -1e30), "DEM has no-data cells; handle them before packing"

    q = np.round(z * 10.0).astype(np.int32)          # decimetres
    assert q.min() > -32768 and q.max() < 32767
    d = q.copy()
    d[:, 1:] = q[:, 1:] - q[:, :-1]                  # horizontal delta
    d[1:, 0] = q[1:, 0] - q[:-1, 0]                  # first column: vertical delta
    assert np.abs(d[:, 1:]).max() < 32767
    raw = d.astype("<i2").tobytes()
    packed = gzip.compress(raw, 9)
    write_js("dem.js", "MM_DEM", {
        "source": "MRO CTX stereo DTM, Jezero (JEZ_ctx_B_soc_008_DTM_MOLAtopography_DeltaGeoid_20m), USGS Astrogeology / NASA Mars Trek",
        "width": w, "height": h, "pixel_m": px,
        "west": west, "east": east, "south": south, "north": north,
        "radius_m": MARS_R, "unit": "decimetre", "encoding": "int16-le, delta, gzip, base64",
        "min_m": float(z.min()), "max_m": float(z.max()),
        "b64": base64.b64encode(packed).decode("ascii"),
    })
    return dict(z=z, west=west, east=east, south=south, north=north, w=w, h=h)


# ----------------------------------------------------------------------------
# 2. Perseverance traverse, waypoints and Ingenuity flights (M2020 mission, MMGIS)
# ----------------------------------------------------------------------------
def simplify(points, tol):
    """Douglas-Peucker on [lon, lat] pairs; tol in degrees."""
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]; bx, by = points[b]
        dx, dy = bx - ax, by - ay
        n = math.hypot(dx, dy) or 1e-12
        best, bi = 0.0, -1
        for i in range(a + 1, b):
            px_, py_ = points[i]
            dist = abs((px_ - ax) * dy - (py_ - ay) * dx) / n
            if dist > best:
                best, bi = dist, i
        if best > tol and bi > 0:
            keep[bi] = True
            stack.append((a, bi)); stack.append((bi, b))
    return [p for p, k in zip(points, keep) if k]


def build_rover(dem):
    trav = json.load(open(os.path.join(RAW, "mmap_m20_traverse.json")))["features"]
    wps = json.load(open(os.path.join(RAW, "mmap_m20_waypoints.json")))["features"]
    heli = json.load(open(os.path.join(RAW, "mmap_m20_heli_path.json")))["features"]

    def coords(geom):
        if geom["type"] == "LineString":
            return [geom["coordinates"]]
        return geom["coordinates"]

    tol = 1.5 / (MARS_R * math.pi / 180)  # ~1.5 m
    line, last_sol = [], 0
    for f in sorted(trav, key=lambda f: f["properties"]["sol"]):
        for part in coords(f["geometry"]):
            pts = [[c[0], c[1]] for c in part]
            line.extend(pts)
        last_sol = max(last_sol, f["properties"]["sol"])
    line = simplify(line, tol)
    line = [[round(p[0], 6), round(p[1], 6)] for p in line]

    wp_out = []
    for f in wps:
        p = f["properties"]
        wp_out.append([p["sol"], round(p["lon"], 6), round(p["lat"], 6),
                       round(p["elev_geoid"], 1), round(p.get("dist_total_m", 0) or 0)])

    flights = []
    for f in heli:
        p = f["properties"]
        pts = []
        for part in coords(f["geometry"]):
            pts.extend([[c[0], c[1]] for c in part])
        pts = simplify(pts, tol)
        flights.append({"n": p["Flight"], "sol": p["Sol"], "len_m": round(p.get("Length_m") or 0, 1),
                        "pts": [[round(a, 6), round(b, 6)] for a, b in pts]})

    write_js("rover.js", "MM_ROVER", {
        "source": "NASA/JPL-Caltech Mars 2020 mission, 'Where is Perseverance?' map layers (mars.nasa.gov/mmgis-maps/M20)",
        "last_sol": last_sol,
        "total_km": round(wps[-1]["properties"].get("dist_km", 0), 2),
        "traverse": line,
        "waypoint_fields": ["sol", "lon", "lat", "elev_m", "odometer_m"],
        "waypoints": wp_out,
        "flights": flights,
    })
    return wps


