def build_targets(wps, dem):
    sols = [f["properties"]["sol"] for f in wps]
    out = []
    for key, name, sol, kind, unit, sample, blurb, stop in TARGETS:
        idx = max(i for i, s in enumerate(sols) if s <= sol)
        p = wps[idx]["properties"]
        out.append({"id": key, "name": name, "kind": kind, "sol": sol, "unit": unit, "sample": sample,
                    "why": blurb, "stop_min": stop, "lon": round(p["lon"], 6), "lat": round(p["lat"], 6),
                    "elev_m": round(p["elev_geoid"], 1),
                    "source": "Position: Perseverance localization, sol %d waypoint (NASA/JPL-Caltech)" % p["sol"]})
    write_js("targets.js", "MM_TARGETS_ROVER", out)


