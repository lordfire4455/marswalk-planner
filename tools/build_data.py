# 3. Weather: Curiosity REMS (full record) and Perseverance MEDA (latest report)
# ----------------------------------------------------------------------------
def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def build_weather():
    rems = json.load(open(os.path.join(RAW, "mmap_wx_msl.json")))["soles"]
    meda = json.load(open(os.path.join(RAW, "mmap_wx_m20.json")))["sols"]
    BIN = 10
    bins = [dict(n=0, tmin=[], tmax=[], gmin=[], gmax=[], p=[], uv={}, op={}) for _ in range(360 // BIN)]
    for s in rems:
        ls = num(s.get("ls"))
        if ls is None:
            continue
        b = bins[int(ls % 360) // BIN]
        b["n"] += 1
        for key, dst in (("min_temp", "tmin"), ("max_temp", "tmax"), ("min_gts_temp", "gmin"),
                         ("max_gts_temp", "gmax"), ("pressure", "p")):
            v = num(s.get(key))
            if v is not None:
                b[dst].append(v)
        uv = s.get("local_uv_irradiance_index")
        if uv and uv != "--":
            b["uv"][uv] = b["uv"].get(uv, 0) + 1
        op = s.get("atmo_opacity")
        if op and op != "--":
            b["op"][op] = b["op"].get(op, 0) + 1

    def stat(a):
        if not a:
            return None
        a = np.array(a)
        return [round(float(np.percentile(a, 10)), 1), round(float(np.median(a)), 1), round(float(np.percentile(a, 90)), 1)]

    clim = []
    for i, b in enumerate(bins):
        clim.append({"ls0": i * BIN, "n": b["n"], "air_min": stat(b["tmin"]), "air_max": stat(b["tmax"]),
                     "ground_min": stat(b["gmin"]), "ground_max": stat(b["gmax"]), "pressure": stat(b["p"]),
                     "uv": b["uv"], "opacity": b["op"]})
    latest_rems = []
    for s in rems[:10]:
        latest_rems.append({k: s.get(k) for k in ("terrestrial_date", "sol", "ls", "min_temp", "max_temp", "pressure",
                                                   "min_gts_temp", "max_gts_temp", "atmo_opacity", "sunrise", "sunset",
                                                   "local_uv_irradiance_index")})
    write_js("weather.js", "MM_WEATHER", {
        "rems": {
            "source": "Curiosity REMS (Centro de Astrobiologia CSIC-INTA / NASA JPL), Gale Crater 4.6S 137.4E, mars.nasa.gov weather feed",
            "sols_in_record": len(rems), "first_date": rems[-1]["terrestrial_date"], "last_date": rems[0]["terrestrial_date"],
            "bin_deg": BIN, "stat_fields": ["p10", "median", "p90"], "climatology": clim, "latest": latest_rems,
        },
        "meda": {
            "source": "Perseverance MEDA (Centro de Astrobiologia CSIC-INTA / NASA JPL), Jezero Crater, mars.nasa.gov weather feed",
            "latest": meda,
        },
        "live_feeds": {
            "meda": "https://mars.nasa.gov/rss/api/?feed=weather&category=mars2020&feedtype=json",
            "rems": "https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json",
        },
    })


