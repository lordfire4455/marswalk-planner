# 4. CRISM mineral browse products (MRO CRISM MTRDR, PDS Geosciences Node)
# ----------------------------------------------------------------------------
CRISM_SCENES = {
    # id: (west, east, south, north, acquired)   -- from the PDS .lbl files
    "hrl000040ff": (77.2755600, 77.5611340, 18.2767400, 18.7324270, "2007-01-29"),
    "frt00005850": (77.1925020, 77.5035510, 18.1123950, 18.4289460, "2007-04-21"),
    "frt00005c5e": (77.2791950, 77.5587930, 18.3646720, 18.6350470, "2007-05-19"),
    "frt000066a4": (77.4692050, 77.7321340, 18.3423180, 18.5871740, "2007-06-27"),
}
CRISM_PRODUCTS = ["maf", "car", "pfm"]


def build_crism():
    scenes = []
    for sid, (w, e, s, n, date) in CRISM_SCENES.items():
        entry = {"id": sid.upper(), "date": date, "bounds": [[s, w], [n, e]], "files": {}}
        for prod in CRISM_PRODUCTS:
            name = "mmap_crism_%s_07_br%sj_mtr3.png" % (sid, prod)
            src = os.path.join(RAW, name)
            if not os.path.exists(src):
                print("  missing", name)
                continue
            im = np.array(Image.open(src).convert("RGBA"))
            rgb = im[:, :, :3].astype(np.int32)
            empty = (rgb.sum(axis=2) == 0) | (im[:, :, 3] == 0)
            im[:, :, 3] = np.where(empty, 0, 255).astype(np.uint8)
            out_name = "crism/%s_%s.png" % (sid, prod)
            Image.fromarray(im, "RGBA").save(os.path.join(OUT, out_name), optimize=True)
            entry["files"][prod] = "data/" + out_name
        scenes.append(entry)
    write_js("crism.js", "MM_CRISM", {
        "source": "MRO CRISM MTRDR browse products (Viviano-Beck et al. 2014), NASA PDS Geosciences Node, volume MROCR_4001",
        "scenes": scenes,
    })


